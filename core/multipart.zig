//! `multipart/form-data` bodies, for `UpdateService` firmware push.
//!
//! DSP0266 §13.4 has a client push firmware by `POST`ing a multipart form to
//! `UpdateService.MultipartHttpPushUri`, with an `UpdateParameters` part
//! carrying JSON and an `UpdateFile` part carrying the image. An image is far
//! too large to hold in memory, so a `Form` is not a buffer: it is a sequence
//! of segments — generated headers interleaved with the caller's data — read
//! as the request is written.
//!
//! `Form` produces a `std.Io.Reader`, which is all `RequestBody.stream` needs,
//! so nothing here knows about HTTP and any transport can send one.

const std = @import("std");

const Allocator = std.mem.Allocator;
const Limit = std.Io.Limit;
const Reader = std.Io.Reader;
const Writer = std.Io.Writer;

/// Bytes of randomness in a generated boundary. RFC 2046 caps a boundary at
/// 70 characters; 24 bytes of base64 is 32, well inside it and far beyond any
/// realistic chance of appearing in an uploaded image.
pub const boundary_entropy = 24;
pub const boundary_len = std.base64.url_safe_no_pad.Encoder.calcSize(boundary_entropy);
pub const Boundary = [boundary_len]u8;

/// A boundary that will not occur in the parts.
///
/// The caller supplies the randomness: `redfish_core` takes no `std.Io`, and a
/// seeded generator makes a form reproducible under test.
pub fn randomBoundary(random: std.Random) Boundary {
    var entropy: [boundary_entropy]u8 = undefined;
    random.bytes(&entropy);

    var boundary: Boundary = undefined;
    _ = std.base64.url_safe_no_pad.Encoder.encode(&boundary, &entropy);
    return boundary;
}

/// Where a part's data comes from.
pub const Source = union(enum) {
    /// Data already in memory, such as an encoded JSON parameters part.
    bytes: []const u8,
    /// Data read as the form is sent.
    stream: Stream,

    pub const Stream = struct {
        /// Read to end of stream. Borrowed; must outlive the form.
        reader: *Reader,
        /// The length, when known. Every part needs one for the form as a
        /// whole to have a `Content-Length`.
        len: ?u64 = null,
    };
};

/// One form part.
pub const Part = struct {
    /// The `name` parameter of `Content-Disposition`.
    name: []const u8,
    /// The `filename` parameter, which a service uses to name the staged
    /// image. Omitted when null.
    filename: ?[]const u8 = null,
    /// The part's `Content-Type`. Omitted when null, which makes it
    /// `text/plain` per RFC 7578 — so a binary part should always set it.
    content_type: ?[]const u8 = null,
    source: Source,
};

pub const BuildError = error{
    /// A name or filename contained a quote, a backslash, or a line break,
    /// none of which can be expressed in a `Content-Disposition` parameter.
    /// Escaping them is not interoperable, so they are refused instead.
    InvalidPartName,
} || Allocator.Error;

/// One segment of the body: either generated bytes or a caller's data.
const Segment = union(enum) {
    bytes: []const u8,
    stream: Source.Stream,

    fn len(self: Segment) ?u64 {
        return switch (self) {
            .bytes => |bytes| bytes.len,
            .stream => |source| source.len,
        };
    }
};

/// A `multipart/form-data` body, ready to be read.
///
/// Everything generated lives in the allocator passed to `init`; the parts'
/// own data is borrowed and must outlive the form.
pub const Form = struct {
    boundary: Boundary,
    segments: []const Segment,
    content_type_header: []const u8,

    /// Lays out the form. Nothing is read from the parts here.
    pub fn init(
        arena: Allocator,
        boundary: Boundary,
        parts: []const Part,
    ) BuildError!Form {
        var segments: std.ArrayList(Segment) = .empty;

        for (parts) |part| {
            if (!isValidParameter(part.name)) return BuildError.InvalidPartName;
            if (part.filename) |filename| {
                if (!isValidParameter(filename)) return BuildError.InvalidPartName;
            }

            var header: std.ArrayList(u8) = .empty;
            try header.print(arena, "--{s}\r\nContent-Disposition: form-data; name=\"{s}\"", .{
                &boundary,
                part.name,
            });
            if (part.filename) |filename| {
                try header.print(arena, "; filename=\"{s}\"", .{filename});
            }
            try header.appendSlice(arena, "\r\n");
            if (part.content_type) |content_type| {
                try header.print(arena, "Content-Type: {s}\r\n", .{content_type});
            }
            try header.appendSlice(arena, "\r\n");

            try segments.append(arena, .{ .bytes = try header.toOwnedSlice(arena) });
            try segments.append(arena, switch (part.source) {
                .bytes => |bytes| .{ .bytes = bytes },
                .stream => |source| .{ .stream = source },
            });
            try segments.append(arena, .{ .bytes = "\r\n" });
        }

        try segments.append(arena, .{
            .bytes = try std.fmt.allocPrint(arena, "--{s}--\r\n", .{&boundary}),
        });

        return .{
            .boundary = boundary,
            .segments = try segments.toOwnedSlice(arena),
            .content_type_header = try std.fmt.allocPrint(
                arena,
                "multipart/form-data; boundary={s}",
                .{&boundary},
            ),
        };
    }

    /// The `Content-Type` to send, boundary included.
    pub fn contentType(self: Form) []const u8 {
        return self.content_type_header;
    }

    /// The body's total length, or null if any part's length is unknown.
    ///
    /// A BMC that will not accept chunked transfer encoding needs this, which
    /// is why `Source.Stream.len` is worth supplying whenever the caller knows
    /// it — a file's size normally is known.
    pub fn contentLength(self: Form) ?u64 {
        var total: u64 = 0;
        for (self.segments) |segment| total += segment.len() orelse return null;
        return total;
    }

    /// A reader over the whole body.
    ///
    /// The returned value must not be moved: `interface` is handed out by
    /// pointer.
    pub fn reader(self: *const Form) FormReader {
        return .{
            .interface = .{
                .vtable = &.{ .stream = FormReader.streamImpl },
                .buffer = &.{},
                .seek = 0,
                .end = 0,
            },
            .segments = self.segments,
        };
    }
};

/// Reads a `Form`'s segments end to end as one stream.
pub const FormReader = struct {
    interface: Reader,
    segments: []const Segment,
    /// The segment being read.
    index: usize = 0,
    /// Bytes taken from the current segment.
    offset: usize = 0,

    fn streamImpl(r: *Reader, w: *Writer, limit: Limit) Reader.StreamError!usize {
        const self: *FormReader = @fieldParentPtr("interface", r);

        while (self.index < self.segments.len) {
            switch (self.segments[self.index]) {
                .bytes => |bytes| {
                    const rest = bytes[self.offset..];
                    if (rest.len == 0) {
                        self.advance();
                        continue;
                    }
                    const chunk = limit.sliceConst(rest);
                    try w.writeAll(chunk);
                    self.offset += chunk.len;
                    if (self.offset == bytes.len) self.advance();
                    return chunk.len;
                },
                .stream => |source| {
                    // A short read is fine — it is the caller of `stream` that
                    // decides when it has enough. Only end of stream moves us
                    // on to the next part.
                    return source.reader.stream(w, limit) catch |err| switch (err) {
                        error.EndOfStream => {
                            self.advance();
                            continue;
                        },
                        else => |e| return e,
                    };
                },
            }
        }
        return error.EndOfStream;
    }

    fn advance(self: *FormReader) void {
        self.index += 1;
        self.offset = 0;
    }
};

/// Whether a `Content-Disposition` parameter can be written verbatim.
fn isValidParameter(value: []const u8) bool {
    for (value) |byte| {
        switch (byte) {
            '"', '\\', '\r', '\n' => return false,
            else => {},
        }
    }
    return true;
}

const testing = std.testing;

const test_boundary: Boundary = "0123456789abcdefghijklmnopqrstuv".*;

/// Reads a form to the end, so a test can look at the bytes that would go on
/// the wire.
fn render(gpa: Allocator, form: *const Form) ![]u8 {
    var form_reader = form.reader();

    var out: std.Io.Writer.Allocating = .init(gpa);
    errdefer out.deinit();

    _ = try form_reader.interface.streamRemaining(&out.writer);
    return out.toOwnedSlice();
}

test "a boundary is generated from the caller's randomness" {
    var prng: std.Random.DefaultPrng = .init(0x5eed);
    const first = randomBoundary(prng.random());
    const second = randomBoundary(prng.random());

    try testing.expectEqual(boundary_len, first.len);
    try testing.expect(!std.mem.eql(u8, &first, &second));
    for (first) |byte| try testing.expect(std.ascii.isAlphanumeric(byte) or byte == '-' or byte == '_');

    // Seeded, so a form is reproducible under test.
    var replay: std.Random.DefaultPrng = .init(0x5eed);
    try testing.expectEqualStrings(&first, &randomBoundary(replay.random()));
}

test "a single part renders with its headers" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();

    const form: Form = try .init(arena.allocator(), test_boundary, &.{.{
        .name = "UpdateParameters",
        .content_type = "application/json",
        .source = .{ .bytes = "{\"Targets\":[]}" },
    }});

    const body = try render(testing.allocator, &form);
    defer testing.allocator.free(body);

    try testing.expectEqualStrings(
        "--0123456789abcdefghijklmnopqrstuv\r\n" ++
            "Content-Disposition: form-data; name=\"UpdateParameters\"\r\n" ++
            "Content-Type: application/json\r\n" ++
            "\r\n" ++
            "{\"Targets\":[]}\r\n" ++
            "--0123456789abcdefghijklmnopqrstuv--\r\n",
        body,
    );
}

test "the Redfish update form renders both parts" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();

    var image: Reader = .fixed("firmware-bytes");
    const form: Form = try .init(arena.allocator(), test_boundary, &.{
        .{
            .name = "UpdateParameters",
            .content_type = "application/json",
            .source = .{ .bytes = "{\"Targets\":[\"/redfish/v1/Chassis/1\"]}" },
        },
        .{
            .name = "UpdateFile",
            .filename = "firmware.bin",
            .content_type = "application/octet-stream",
            .source = .{ .stream = .{ .reader = &image, .len = "firmware-bytes".len } },
        },
    });

    const body = try render(testing.allocator, &form);
    defer testing.allocator.free(body);

    try testing.expectEqualStrings(
        "--0123456789abcdefghijklmnopqrstuv\r\n" ++
            "Content-Disposition: form-data; name=\"UpdateParameters\"\r\n" ++
            "Content-Type: application/json\r\n" ++
            "\r\n" ++
            "{\"Targets\":[\"/redfish/v1/Chassis/1\"]}\r\n" ++
            "--0123456789abcdefghijklmnopqrstuv\r\n" ++
            "Content-Disposition: form-data; name=\"UpdateFile\"; filename=\"firmware.bin\"\r\n" ++
            "Content-Type: application/octet-stream\r\n" ++
            "\r\n" ++
            "firmware-bytes\r\n" ++
            "--0123456789abcdefghijklmnopqrstuv--\r\n",
        body,
    );
    try testing.expectEqualStrings(
        "multipart/form-data; boundary=0123456789abcdefghijklmnopqrstuv",
        form.contentType(),
    );
    try testing.expectEqual(@as(?u64, body.len), form.contentLength());
}

test "a part with no content type omits the header" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();

    const form: Form = try .init(arena.allocator(), test_boundary, &.{.{
        .name = "Plain",
        .source = .{ .bytes = "x" },
    }});

    const body = try render(testing.allocator, &form);
    defer testing.allocator.free(body);

    try testing.expect(std.mem.indexOf(u8, body, "Content-Type") == null);
    try testing.expect(std.mem.indexOf(u8, body, "name=\"Plain\"\r\n\r\nx") != null);
}

test "an empty form is just the closing boundary" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();

    const form: Form = try .init(arena.allocator(), test_boundary, &.{});

    const body = try render(testing.allocator, &form);
    defer testing.allocator.free(body);

    try testing.expectEqualStrings("--0123456789abcdefghijklmnopqrstuv--\r\n", body);
    try testing.expectEqual(@as(?u64, body.len), form.contentLength());
}

test "an empty part still renders its boundary and headers" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();

    var empty: Reader = .fixed("");
    const form: Form = try .init(arena.allocator(), test_boundary, &.{
        .{ .name = "Nothing", .source = .{ .bytes = "" } },
        .{ .name = "AlsoNothing", .source = .{ .stream = .{ .reader = &empty, .len = 0 } } },
    });

    const body = try render(testing.allocator, &form);
    defer testing.allocator.free(body);

    try testing.expect(std.mem.indexOf(u8, body, "name=\"Nothing\"\r\n\r\n\r\n") != null);
    try testing.expect(std.mem.indexOf(u8, body, "name=\"AlsoNothing\"\r\n\r\n\r\n") != null);
    try testing.expectEqual(@as(?u64, body.len), form.contentLength());
}

test "a stream of unknown length leaves the form unmeasured" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();

    var image: Reader = .fixed("bytes");
    const form: Form = try .init(arena.allocator(), test_boundary, &.{.{
        .name = "UpdateFile",
        .source = .{ .stream = .{ .reader = &image } },
    }});

    try testing.expectEqual(@as(?u64, null), form.contentLength());
}

test "a name that cannot be quoted is refused" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();

    for ([_][]const u8{ "bad\"name", "back\\slash", "line\r\nbreak" }) |name| {
        try testing.expectError(BuildError.InvalidPartName, Form.init(
            arena.allocator(),
            test_boundary,
            &.{.{ .name = name, .source = .{ .bytes = "x" } }},
        ));
        try testing.expectError(BuildError.InvalidPartName, Form.init(
            arena.allocator(),
            test_boundary,
            &.{.{ .name = "ok", .filename = name, .source = .{ .bytes = "x" } }},
        ));
    }
}

test "a form reads the same in one pass as in many small ones" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();

    var image: Reader = .fixed("0123456789" ** 8);
    const form: Form = try .init(arena.allocator(), test_boundary, &.{
        .{ .name = "UpdateParameters", .source = .{ .bytes = "{}" } },
        .{ .name = "UpdateFile", .source = .{ .stream = .{ .reader = &image, .len = 80 } } },
    });

    const whole = try render(testing.allocator, &form);
    defer testing.allocator.free(whole);

    // Again, three bytes at a time, which forces `stream` to resume mid
    // segment on nearly every call.
    var replay: Reader = .fixed("0123456789" ** 8);
    const again: Form = try .init(arena.allocator(), test_boundary, &.{
        .{ .name = "UpdateParameters", .source = .{ .bytes = "{}" } },
        .{ .name = "UpdateFile", .source = .{ .stream = .{ .reader = &replay, .len = 80 } } },
    });

    var again_reader = again.reader();
    var out: std.Io.Writer.Allocating = .init(testing.allocator);
    defer out.deinit();

    while (true) {
        _ = again_reader.interface.stream(&out.writer, .limited(3)) catch |err| switch (err) {
            error.EndOfStream => break,
            else => return err,
        };
    }

    try testing.expectEqualStrings(whole, out.written());
}
